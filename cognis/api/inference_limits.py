"""Bound inference request bodies before JSON parsing."""

from __future__ import annotations

from starlette.types import ASGIApp, Message, Receive, Scope, Send


class InferenceBodyLimitMiddleware:
    def __init__(self, app: ASGIApp, max_bytes: int = 8 * 1024 * 1024) -> None:
        self.app = app
        self.max_bytes = max_bytes

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        if (
            scope["type"] != "http"
            or scope.get("method") != "POST"
            or not str(scope.get("path", "")).startswith("/v1/")
        ):
            await self.app(scope, receive, send)
            return
        body = bytearray()
        while True:
            message = await receive()
            if message["type"] == "http.disconnect":
                return
            body.extend(message.get("body", b""))
            if len(body) > self.max_bytes:
                payload = b'{"error":{"message":"Inference request exceeds 8 MiB","type":"invalid_request_error","code":"request_too_large"}}'
                await send(
                    {
                        "type": "http.response.start",
                        "status": 413,
                        "headers": [(b"content-type", b"application/json")],
                    }
                )
                await send({"type": "http.response.body", "body": payload})
                return
            if not message.get("more_body"):
                break
        replayed = False

        async def replay() -> Message:
            nonlocal replayed
            if replayed:
                return await receive()
            replayed = True
            return {"type": "http.request", "body": bytes(body), "more_body": False}

        await self.app(scope, replay, send)
